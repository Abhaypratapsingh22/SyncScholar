/**
 * @file vectorSearchService.js
 * @description Vector retrieval service for SyncScholar Adaptive RAG.
 * Embeds student queries at 768 dimensions using gemini-embedding-001, executes
 * MongoDB Atlas $vectorSearch aggregation with dynamic pre-filters, and enforces
 * minimum relevance thresholds to prevent out-of-syllabus hallucinations.
 */

import { GoogleGenAI } from '@google/genai';
import { env } from '../config/env.js';
import CurriculumChunk from '../models/CurriculumChunk.js';

// Initialize singleton Google Gen AI client with validated API key
const ai = new GoogleGenAI({ apiKey: env.GEMINI_API_KEY });

// Constants adhering to prompt mandates
const EMBEDDING_MODEL = 'gemini-embedding-001';
const EMBEDDING_DIMENSIONS = 768;
const ATLAS_SEARCH_INDEX = 'vector_index';
const NUM_CANDIDATES = 40;
const SEARCH_LIMIT = 4;
// Atlas Vector Search normalizes cosine similarity to (1 + cos) / 2.
// Unrelated passages score ~0.70-0.74, while aligned curriculum queries score >0.80.
const MIN_RELEVANCE_THRESHOLD = 0.78;

/**
 * Generates 768-dimensional float embedding for a query with exponential backoff on HTTP 429.
 *
 * @param {string} text - Query text to embed
 * @param {number} [maxRetries=4] - Maximum retry attempts
 * @returns {Promise<number[]>} 768-dimensional float vector
 */
export async function embedQueryWithRetry(text, maxRetries = 4) {
  let attempt = 0;
  let delay = 1000;

  while (attempt < maxRetries) {
    try {
      const response = await ai.models.embedContent({
        model: EMBEDDING_MODEL,
        contents: text,
        config: {
          outputDimensionality: EMBEDDING_DIMENSIONS,
        },
      });

      const embeddingValues = response.embeddings?.[0]?.values;
      if (!Array.isArray(embeddingValues) || embeddingValues.length !== EMBEDDING_DIMENSIONS) {
        throw new Error(
          `Unexpected embedding dimensions: expected ${EMBEDDING_DIMENSIONS}, received ${embeddingValues?.length}`
        );
      }

      return embeddingValues;
    } catch (err) {
      attempt++;
      const isRateLimit =
        err?.status === 429 ||
        err?.message?.includes('429') ||
        err?.message?.includes('RESOURCE_EXHAUSTED');

      if (isRateLimit && attempt < maxRetries) {
        console.warn(
          `[vectorSearchService] Rate limit hit. Backing off ${delay}ms (Attempt ${attempt}/${maxRetries})...`
        );
        await new Promise((resolve) => setTimeout(resolve, delay));
        delay *= 2;
      } else {
        throw err;
      }
    }
  }

  throw new Error(`Embedding generation failed after ${maxRetries} attempts.`);
}

/**
 * Performs adaptive MongoDB Atlas $vectorSearch against curriculum_chunks.
 *
 * @param {object} params
 * @param {string} params.query - Student's question text
 * @param {object} params.filter - Pre-filter generated by adaptiveFilterService
 * @param {number} [params.minRelevanceScore=MIN_RELEVANCE_THRESHOLD] - Cutoff score
 * @returns {Promise<{
 *   chunks: Array<{
 *     _id: string,
 *     text: string,
 *     metadata: object,
 *     vectorSearchScore: number
 *   }>,
 *   isOutOfSyllabus: boolean,
 *   topScore: number,
 *   refusalReason?: string
 * }>}
 */
export async function retrieveRelevantChunks({
  query,
  filter,
  minRelevanceScore = MIN_RELEVANCE_THRESHOLD,
}) {
  if (!query || typeof query !== 'string' || query.trim().length === 0) {
    throw new Error('retrieveRelevantChunks requires a non-empty query string.');
  }

  // 1. Generate 768-dimensional query embedding via gemini-embedding-001
  const queryVector = await embedQueryWithRetry(query.trim());

  // 2. Execute Atlas $vectorSearch pipeline with adaptive pre-filter
  const pipeline = [
    {
      $vectorSearch: {
        index: ATLAS_SEARCH_INDEX,
        path: 'embedding',
        queryVector,
        numCandidates: NUM_CANDIDATES,
        limit: SEARCH_LIMIT,
        filter: filter,
      },
    },
    {
      $project: {
        _id: 1,
        text: 1,
        metadata: 1,
        vectorSearchScore: { $meta: 'vectorSearchScore' },
      },
    },
  ];

  const candidateChunks = await CurriculumChunk.aggregate(pipeline);

  // 3. Relevance threshold validation (Zero Out-of-Syllabus Hallucination)
  const relevantChunks = candidateChunks.filter(
    (chunk) => typeof chunk.vectorSearchScore === 'number' && chunk.vectorSearchScore >= minRelevanceScore
  );

  const topScore = candidateChunks.length > 0 ? candidateChunks[0].vectorSearchScore : 0;

  // If zero chunks exceed threshold, trigger safe refusal without calling LLM
  if (relevantChunks.length === 0) {
    return {
      chunks: [],
      isOutOfSyllabus: true,
      topScore: Number(topScore.toFixed(4)),
      refusalReason:
        'This topic appears outside your current grade syllabus. I can only guide you on concepts covered in your approved textbooks.',
    };
  }

  return {
    chunks: relevantChunks.map((c) => ({
      _id: c._id,
      text: c.text,
      metadata: c.metadata,
      vectorSearchScore: Number(c.vectorSearchScore.toFixed(4)),
    })),
    isOutOfSyllabus: false,
    topScore: Number(topScore.toFixed(4)),
  };
}

export default {
  retrieveRelevantChunks,
  embedQueryWithRetry,
};
